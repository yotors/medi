#!/usr/bin/env python3
"""Create project-local Codex settings. Refuse to overwrite existing settings."""
import json
import os
from pathlib import Path
import tomllib

root = Path(__file__).resolve().parents[1]
target = root / '.codex/config.toml'
if target.exists():
    raise SystemExit(f'{target} already exists; inspect and merge any changes explicitly.')
quote = json.dumps
text = f'''# Generated by tooling/configure-codex.py; regenerate if this folder moves.
# Existing account settings, models and permission policies are inherited.
[shell_environment_policy.set]
PATH = {quote(str(root / '.venv/bin') + ':' + str(root / 'node_modules/.bin') + ':' + os.environ['PATH'])}
UV_CACHE_DIR = {quote(str(root / '.cache/uv'))}
IMPECCABLE_HOME = {quote(str(root / '.cache/impeccable'))}
PLAYWRIGHT_BROWSERS_PATH = {quote(str(root / '.cache/ms-playwright'))}

[mcp_servers.context7]
command = "node"
args = [{quote(str(root / 'node_modules/@upstash/context7-mcp/dist/index.js'))}]
startup_timeout_sec = 30
tool_timeout_sec = 60

[mcp_servers.playwright]
command = "node"
args = [{quote(str(root / 'tooling/playwright-mcp.mjs'))}]
cwd = {quote(str(root))}
startup_timeout_sec = 30
tool_timeout_sec = 60

[mcp_servers.openaiDeveloperDocs]
url = "https://developers.openai.com/mcp"
startup_timeout_sec = 30
tool_timeout_sec = 60
'''
tomllib.loads(text)
target.parent.mkdir(exist_ok=True)
target.write_text(text)
print(f'Created {target}')
